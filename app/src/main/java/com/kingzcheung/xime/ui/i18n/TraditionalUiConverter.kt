    private val cache = object : LinkedHashMap<String, String>(256, 0.75f, true) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, String>?) = size > CACHE_SIZE
    }

    fun convert(text: String): String {
        if (text.isEmpty() || text == "简体中文" || !UiTranslations.hasHan(text) || text.length > MAX_CONVERTIBLE) {
            return text
        }
        synchronized(cache) { cache[text]?.let { return it } }

        val sb = StringBuilder(text.length)
        var cursor = 0
        for (match in PHRASE_REGEX.findAll(text)) {
            if (match.range.first > cursor) {
                sb.append(convertSegment(text.substring(cursor, match.range.first)))
            }
            sb.append(PHRASES[match.value] ?: match.value)
            cursor = match.range.last + 1
        }
        if (cursor < text.length) {
            sb.append(convertSegment(text.substring(cursor)))
        }
        val result = sb.toString()
        synchronized(cache) { cache[text] = result }
        return result
    }

    private fun convertSegment(segment: String): String {
        if (!UiTranslations.hasHan(segment)) return segment
        val converted = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            val tr = icuTransliterator
            if (tr is android.icu.text.Transliterator) {
                runCatching { tr.transliterate(segment) }.getOrElse { convertByCharMap(segment) }
            } else {
                convertByCharMap(segment)
            }
        } else {
            convertByCharMap(segment)
        }
        return normalizeTaiwanVariants(converted)
    }

    private fun convertByCharMap(segment: String): String {
        val sb = StringBuilder(segment.length)
        for (ch in segment) {
            sb.append(CHAR_MAP[ch] ?: ch)
        }
        return sb.toString()
    }

    private fun normalizeTaiwanVariants(segment: String): String {
        var changed = false
        val sb = StringBuilder(segment.length)
        for (ch in segment) {
            val mapped = TAIWAN_VARIANT_CHAR_MAP[ch]
            if (mapped != null) {
                sb.append(mapped)
                changed = true
            } else {
                sb.append(ch)
            }
        }
        return if (changed) sb.toString() else segment
    }
